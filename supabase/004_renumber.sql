alter table public.requests alter column no set generated by default;
with o as (select id, row_number() over (order by requested_at nulls last, created_at, no) as n from public.requests)
update public.requests r set no = -o.n from o where r.id = o.id;
update public.requests set no = -no where no < 0;
select setval(pg_get_serial_sequence('public.requests','no'), (select max(no) from public.requests));
